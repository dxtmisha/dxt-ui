import { afterEach, describe, expect, it, vi } from 'vitest'
import { LibraryItems } from '../LibraryItems'
import { PropertiesFile } from '../../Properties/PropertiesFile'
import { PropertiesConfig } from '../../Properties/PropertiesConfig'

class TestLibraryItems extends LibraryItems {
  public testGetComponents() {
    return this.getComponents()
  }

  public testInitItems() {
    return this.initItems()
  }
}

describe('LibraryItems', () => {
  afterEach(() => {
    vi.restoreAllMocks()
  })

  it('scans components directory and populates component metadata', () => {
    vi.spyOn(PropertiesConfig, 'getDesignName').mockReturnValue('dxt')
    vi.spyOn(PropertiesConfig, 'getProjectName').mockReturnValue('ui-core')
    vi.spyOn(PropertiesFile, 'readDir').mockReturnValue(['Button', 'UserBadge'])
    vi.spyOn(PropertiesFile, 'isDir').mockReturnValue(true)

    const items = new TestLibraryItems()
    const components = items.testGetComponents()

    expect(components).toEqual([
      {
        name: 'button',
        design: 'dxt',
        alias: 'dxt.button',
        codeFull: 'DxtButton',
        dir: 'Button'
      },
      {
        name: 'user-badge',
        design: 'dxt',
        alias: 'dxt.user-badge',
        codeFull: 'DxtUserBadge',
        dir: 'UserBadge'
      }
    ])
  })

  it('calculates counts and retrieves flat component list', () => {
    vi.spyOn(PropertiesConfig, 'getDesignName').mockReturnValue('dxt')
    vi.spyOn(PropertiesConfig, 'getProjectName').mockReturnValue('ui-core')
    vi.spyOn(PropertiesFile, 'readDir').mockReturnValue(['Card'])
    vi.spyOn(PropertiesFile, 'isDir').mockReturnValue(true)

    const items = new LibraryItems()
    expect(items.getCount()).toBe(1)
    expect(items.getComponentList()).toHaveLength(1)
    expect(items.get()[0].name).toBe('dxt')
  })

  it('writes generated files via PropertiesFile.write', () => {
    const writeSpy = vi.spyOn(PropertiesFile, 'write').mockImplementation(() => {})

    const items = new LibraryItems()
    items.write('my-file', ['export const a = 1'], 'ts')

    expect(writeSpy).toHaveBeenCalledWith(
      expect.anything(),
      'my-file',
      expect.stringContaining('// This file is generated by a script, do not edit.'),
      'ts'
    )
  })
})
